SELECT
    C.CUSTOMER_ID,
    C.FIRST_NAME,
    C.LAST_NAME,
    O.TOTAL_AMOUNT
FROM CUSTOMER C
INNER JOIN ORDERS O
    ON C.CUSTOMER_ID = O.CUSTOMER_ID;

SELECT
    O.ORDER_ID,
    PY.PAYMENT_ID,
    PY.PAYMENT_MODE,
    PY.PAYMENT_DATE,
    PY.PAYMENT_AMOUNT,
    PY.PAYMENT_STATUS
FROM ORDERS O
INNER JOIN PAYMENT PY
    ON O.ORDER_ID = PY.ORDER_ID;

SELECT
    P.PRODUCT_ID,
    P.PRODUCT_NAME,
    OD.ORDER_ID,
    OD.QUANTITY,
    OD.UNIT_PRICE,
    OD.SUBTOTAL
FROM PRODUCT P
INNER JOIN ORDER_DETAILS OD
    ON P.PRODUCT_ID = OD.PRODUCT_ID;

SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    O.ORDER_ID,
    O.ORDER_DATE,
    O.TOTAL_AMOUNT
FROM CUSTOMERS C
LEFT JOIN ORDERS O
    ON C.CUSTOMER_ID = O.CUSTOMER_ID;

SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    O.ORDER_ID,
    O.ORDER_DATE,
    O.TOTAL_AMOUNT
FROM CUSTOMERS C
RIGHT JOIN ORDERS O
    ON C.CUSTOMER_ID = O.CUSTOMER_ID;

SELECT
    C.CUSTOMER_ID,
    C.FIRST_NAME || ' ' || C.LAST_NAME AS CUSTOMER_NAME,
    O.ORDER_ID,
    O.ORDER_DATE,
    O.ORDER_STATUS,
    P.PRODUCT_NAME,
    OD.QUANTITY,
    OD.UNIT_PRICE,
    OD.SUBTOTAL,
    O.TOTAL_AMOUNT,
    PY.PAYMENT_MODE,
    PY.PAYMENT_STATUS
FROM CUSTOMER C
INNER JOIN ORDERS O
    ON C.CUSTOMER_ID = O.CUSTOMER_ID
INNER JOIN ORDER_DETAILS OD
    ON O.ORDER_ID = OD.ORDER_ID
INNER JOIN PRODUCT P
    ON OD.PRODUCT_ID = P.PRODUCT_ID
LEFT JOIN PAYMENT PY
    ON O.ORDER_ID = PY.ORDER_ID
ORDER BY O.ORDER_ID;

